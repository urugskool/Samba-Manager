import { MirimSchool, MirimTalent } from '../types/mirim';

/**
 * Gera elenco inicial determinístico de jovens talentos para cada Escola Mirim.
 */
function buildInitialTalents(mirimId: string, basePotential: number, names: Array<{
  name: string;
  role: MirimTalent['role'];
  roleLabel: string;
  age: number;
  targetQuesito: MirimTalent['targetQuesito'];
  ready: boolean;
}>): MirimTalent[] {
  return names.map((item, idx) => ({
    id: `${mirimId}_talento_${idx + 1}`,
    name: item.name,
    role: item.role,
    roleLabel: item.roleLabel,
    age: item.age,
    potential: Math.min(97, Math.max(76, basePotential + (idx === 0 ? 3 : idx === 1 ? 1 : -1))),
    targetQuesito: item.targetQuesito,
    readyToGraduate: item.ready,
  }));
}

